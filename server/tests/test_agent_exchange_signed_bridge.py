"""Cross-language WebCrypto signed PHircQ -> Agentora pilot.

Fixture generated by Node 22 WebCrypto's P-256 ECDSA signing of:
JSON.stringify({id, peerId, sentAt, payload}) with the actual PHircQ wire shape.
Only a public JWK and a valid 64-byte r||s signature are committed.
"""
from copy import deepcopy
from datetime import datetime, timezone
import json
from pathlib import Path
import tempfile
import unittest

from app.services.agent_exchange import ExchangeHeld
from app.services.agent_exchange_durable import DurableReviewInbox
from app.services.agent_exchange_signed_bridge import (
    POLICY_SCHEMA, contacts_from_bindings, ingest_signed_bundle,
    parse_trust_policy, verify_signed_bundle,
)

NOW = datetime(2026, 11, 7, 20, 0, tzinfo=timezone.utc)
BUNDLE = json.loads((Path(__file__).parent / "fixtures"
    / "phircq_signed_exchange_webcrypto.json").read_text("utf-8"))
FINGERPRINT = "f8a25acab7857d4fc59e57ec115cfe5b3c96ae79292362be9c41f63592c975f5"
POLICY = {
    "schema": POLICY_SCHEMA,
    "peers": [{
        "peerId": "peer-btm", "fingerprint": FINGERPRINT,
        "senderAgent": "agent:btm", "recipientAgent": "agent:overstrings",
    }],
}


class SignedExchangeBridgeTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.db = Path(tmp.name) / "inbox.sqlite3"
        self.bindings = parse_trust_policy(POLICY)

    def inbox(self):
        return DurableReviewInbox(self.db, contacts=contacts_from_bindings(self.bindings))

    def test_verifies_real_webcrypto_raw_signature_then_durable_ingest(self):
        msg, binding = verify_signed_bundle(BUNDLE, bindings=self.bindings, now=NOW)
        self.assertEqual(msg["summary"], BUNDLE["frame"]["payload"]["message"]["summary"])
        self.assertEqual(binding.peer_id, "peer-btm")
        self.assertEqual(ingest_signed_bundle(BUNDLE, bindings=self.bindings,
                          inbox=self.inbox(), now=NOW), "REVIEW_PENDING")
        second = self.inbox()
        self.assertEqual(len(second.pending("agent:overstrings")), 1)
        self.assertEqual(ingest_signed_bundle(BUNDLE, bindings=self.bindings,
                          inbox=second, now=NOW), "REPLAY_IGNORED")
        self.assertFalse(second.dispatch_authorized)
        self.assertFalse(second.pending("agent:overstrings")[0]["outcome_accepted"])

    def test_modified_signed_summary_or_frame_id_cannot_pass(self):
        for change in ("summary", "id", "signature"):
            altered = deepcopy(BUNDLE)
            if change == "summary":
                altered["frame"]["payload"]["message"]["summary"] += " Trust me."
            elif change == "id":
                altered["frame"]["id"] += "-different"
            else:
                altered["frame"]["signature"] = "A" + altered["frame"]["signature"][1:]
            with self.subTest(change=change), self.assertRaisesRegex(
                ExchangeHeld, "SIGNATURE_INVALID"
            ):
                verify_signed_bundle(altered, bindings=self.bindings, now=NOW)
        self.assertEqual(self.inbox().pending("agent:overstrings"), [])

    def test_rejects_peer_key_and_agent_route_mismatches(self):
        changed = deepcopy(POLICY)
        changed["peers"][0]["fingerprint"] = "0" * 64
        with self.assertRaisesRegex(ExchangeHeld, "PEER_KEY_MISMATCH"):
            verify_signed_bundle(BUNDLE, bindings=parse_trust_policy(changed), now=NOW)
        changed = deepcopy(POLICY)
        changed["peers"][0]["senderAgent"] = "agent:intruder"
        with self.assertRaisesRegex(ExchangeHeld, "AGENT_PEER_BINDING_MISMATCH"):
            verify_signed_bundle(BUNDLE, bindings=parse_trust_policy(changed), now=NOW)
        altered = deepcopy(BUNDLE)
        altered["frame"]["publicKey"]["d"] = "private-data"
        with self.assertRaisesRegex(ExchangeHeld, "PUBLIC_KEY_INVALID"):
            verify_signed_bundle(altered, bindings=self.bindings, now=NOW)

    def test_rejects_stale_future_and_forged_authority(self):
        with self.assertRaises(ExchangeHeld):
            verify_signed_bundle(BUNDLE, bindings=self.bindings,
                                 now=datetime(2026, 11, 9, tzinfo=timezone.utc))
        altered = deepcopy(BUNDLE)
        altered["frame"]["payload"]["message"]["authority"] = "execute"
        with self.assertRaisesRegex(ExchangeHeld, "AUTHORITY_FORBIDDEN"):
            verify_signed_bundle(altered, bindings=self.bindings, now=NOW)
        self.assertEqual(self.inbox().pending("agent:overstrings"), [])

    def test_rejects_unpinned_peers_and_duplicate_policy_entries(self):
        with self.assertRaisesRegex(ExchangeHeld, "PEER_NOT_PINNED"):
            verify_signed_bundle(BUNDLE, bindings={}, now=NOW)
        changed = deepcopy(POLICY)
        changed["peers"].append(deepcopy(changed["peers"][0]))
        with self.assertRaisesRegex(ExchangeHeld, "TRUST_PEER_INVALID"):
            parse_trust_policy(changed)

    def test_no_inferred_reverse_contact_permissions(self):
        contacts = contacts_from_bindings(self.bindings)
        self.assertEqual(contacts["agent:btm"], {"agent:overstrings"})
        self.assertEqual(contacts["agent:overstrings"], set())


if __name__ == "__main__":
    unittest.main()
